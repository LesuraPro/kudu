  const LOOKALIKE = { А: 'A', В: 'B', Е: 'E', Ё: 'E', К: 'K', М: 'M', Н: 'H', О: 'O', Р: 'P', С: 'C', Т: 'T', Х: 'X' }

  function glyph(ch) {
    const up = ch.toUpperCase()
    return G[up] ?? G[LOOKALIKE[up]] ?? G['?']
  }

  // Строка → массив колонок-битмапов: rows[y][x] = true/false. Между символами 1 пустая колонка.
  function bitmap(text) {
    const rows = Array.from({ length: 7 }, () => [])
    ;[...String(text)].forEach((ch, i) => {
      const g = glyph(ch)
      for (let y = 0; y < 7; y++) {
        if (i > 0) rows[y].push(false)
        for (const c of g[y]) rows[y].push(c === '#')
      }
    })
    return rows
  }

  const width = (text) => bitmap(text)[0].length

  // Нарисовать текст точками. dot — диаметр точки, pitch — шаг сетки.
  function draw(ctx, text, x, y, { pitch = 6, dot = pitch * 0.72, on = '#fff', off = null } = {}) {
    const rows = bitmap(text)
    for (let r = 0; r < 7; r++) {
      for (let c = 0; c < rows[r].length; c++) {
        const lit = rows[r][c]
        if (!lit && !off) continue
        ctx.fillStyle = lit ? on : off
        ctx.beginPath()
        ctx.arc(x + c * pitch + pitch / 2, y + r * pitch + pitch / 2, dot / 2, 0, Math.PI * 2)
        ctx.fill()
      }
    }
    return rows[0].length * pitch
  }

  // Подготовить canvas под размер элемента с учётом масштаба экрана (чётко на 4K)
  function fit(canvas) {
    const dpr = window.devicePixelRatio || 1
    const { width: w, height: h } = canvas.getBoundingClientRect()
    if (canvas.width !== Math.round(w * dpr) || canvas.height !== Math.round(h * dpr)) {
      canvas.width = Math.round(w * dpr)
      canvas.height = Math.round(h * dpr)
    }
    const ctx = canvas.getContext('2d')
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0)
    return { ctx, w, h }
  }

